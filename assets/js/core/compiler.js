// PROMPT COPILOT
// Implementa interface de compilação LaTeX -> PDF (cliente).
// - A engine é injetável/substituível (setEngine)
// - A compilação é assíncrona e não bloqueia a UI
// - Erros são traduzidos para mensagens humanas e associados a blockId
// - Não expõe logs LaTeX crus ao usuário
// - Não realiza compilação nativa aqui; delega à engine (ex: API, WebWorker)

/**
 * Engine contract (informal):
 * A engine deve expor uma função async `compile({ tex, ast, metadata })` que
 * resolve { success: true, pdfBlob } em caso de sucesso ou
 * { success: false, errors: [{ message, log?, line?, blockId? }] } em caso de falha.
 * A propriedade `log` é opcional e nunca deve ser repassada diretamente ao usuário.
 */

let _engine = null;

/** Define a engine de compilação. Use este método para substituir o executor. */
export function setEngine(engine){
  _engine = engine;
}

/** Tradução simples de erros técnicos para mensagens humanas. */
function translateError(err){
  const base = { code: err && err.code ? err.code : 'COMPILE_ERROR', blockId: err && err.blockId ? err.blockId : null };
  let message = 'Erro ao compilar o documento.';
  if (err && err.message) {
    const m = String(err.message || '');
    if (/Undefined control sequence/.test(m)) {
      message = 'Comando LaTeX desconhecido. Verifique equações e pacotes.';
    } else if (/File `.*' not found|Missing image/.test(m)) {
      message = 'Arquivo referenciado (ex.: imagem) não encontrado.';
    } else if (/Package .* Error:/.test(m)) {
      message = 'Erro em pacote LaTeX. Verifique pacotes e configurações do template.';
    } else {
      message = m.replace(/\n+/g, ' ').slice(0, 400);
    }
  }
  return Object.assign(base, { message });
}

/**
 * compileToPdf: API principal. Recebe `tex` (string) ou `ast` já convertido
 * e opções. Retorna { success, pdfBlob?, errors? }.
 *
 * Opções:
 *  - tex: string (pré-gerado) OR ast: object (se tex não fornecido, espera-se
 *    que o chamador gere o LaTeX via generateLaTeX)
 *  - metadata: objeto auxiliar repassado à engine
 *  - timeoutMs: número (opcional)
 */
export async function compileToPdf({ tex = null, ast = null, metadata = {}, timeoutMs = 20000 } = {}){
  if (!_engine) {
    return { success: false, errors: [{ code: 'NO_ENGINE', message: 'Nenhuma engine de compilação configurada.' }] };
  }

  const compilePromise = (async () => {
    try {
      const payload = { tex, ast, metadata };
      const res = await _engine.compile(payload);
      if (!res) {
        return { success: false, errors: [{ code: 'ENGINE_NO_RESPONSE', message: 'Engine não retornou resposta.' }] };
      }
      if (res.success) {
        return { success: true, pdfBlob: res.pdfBlob };
      }
      const errs = (res.errors || []).map(e => translateError(e));
      return { success: false, errors: errs };
    } catch (e) {
      const err = translateError({ message: e && e.message ? e.message : String(e) });
      return { success: false, errors: [err] };
    }
  })();

  const timeoutPromise = new Promise(resolve => setTimeout(() => resolve({ success: false, errors: [{ code: 'TIMEOUT', message: 'Tempo de compilação esgotado.' }] }), timeoutMs));

  const result = await Promise.race([ compilePromise, timeoutPromise ]);
  return result;
}

/** Engine shim de exemplo (simulado) para desenvolvimento. Não exporte em produção. */
export const exampleEngine = {
  async compile({ tex = null, ast = null, metadata = {} } = {}){
    await new Promise(r => setTimeout(r, 250));
    if (!tex && !ast) {
      return { success: false, errors: [{ message: 'Nenhum conteúdo para compilar.' }] };
    }
    const blob = new Blob(["%PDF-1.4\n% Fake PDF generated by exampleEngine\n"], { type: 'application/pdf' });
    return { success: true, pdfBlob: blob };
  }
};

export default { setEngine, compileToPdf, exampleEngine };
